"""v0.2 默认选择、双语和有证据命令合同。"""

import json

import pytest
from click.testing import CliRunner

from repoize.analyzer.project_analyzer import analyze_project
from repoize.cli import GENERATOR_MAP, _load_generator, main
from repoize.formats import split_frontmatter

TARGETS = {
    "agents": "AGENTS.md",
    "claude": "CLAUDE.md",
    "cursor": ".cursor/rules/repoize.mdc",
    "copilot": ".github/copilot-instructions.md",
    "mcp": ".mcp.json",
    "skill": ".claude/skills/project-dev/SKILL.md",
}


def invoke(path, *args):
    return CliRunner().invoke(main, [args[0], str(path), *args[1:]])


def test_init_default_only_agents(tmp_path):
    result = invoke(tmp_path, "init")
    assert result.exit_code == 0, result.output
    assert {p.relative_to(tmp_path).as_posix() for p in tmp_path.rglob("*") if p.is_file()} == {"AGENTS.md"}


def test_init_explicit_types_add_to_agents_and_deduplicate(tmp_path):
    result = invoke(tmp_path, "init", "--type", "claude", "--type", "cursor", "--type", "cursorrules")
    assert result.exit_code == 0, result.output
    assert "生成 3 个文件" in result.output
    assert all((tmp_path / TARGETS[kind]).is_file() for kind in ("agents", "claude", "cursor"))


def test_generate_only_selected_and_alias_deduplicates(tmp_path):
    result = invoke(tmp_path, "generate", "--type", "cursor", "--type", "cursorrules", "--force")
    assert result.exit_code == 0, result.output
    assert "生成 1 个文件" in result.output
    assert not (tmp_path / "AGENTS.md").exists()


def test_init_skips_without_prompt_and_ignores_unselected_errors(tmp_path):
    (tmp_path / "AGENTS.md").write_text("manual", encoding="utf-8")
    (tmp_path / ".mcp.json").write_text("broken", encoding="utf-8")
    (tmp_path / ".cursorrules").write_text("legacy", encoding="utf-8")
    result = invoke(tmp_path, "init")
    assert result.exit_code == 0, result.output
    assert "是否继续" not in result.output
    assert (tmp_path / "AGENTS.md").read_text(encoding="utf-8") == "manual"


def test_update_never_creates_missing_targets(tmp_path):
    result = invoke(tmp_path, "update")
    assert result.exit_code == 0, result.output
    assert list(tmp_path.iterdir()) == []
    result = invoke(tmp_path, "update", "--type", "claude")
    assert result.exit_code == 1, result.output
    assert "generate" in result.output
    assert list(tmp_path.iterdir()) == []


def test_update_discovers_legacy_and_ignores_custom_targets(tmp_path):
    custom = tmp_path / ".cursor/rules/custom.mdc"
    custom.parent.mkdir(parents=True)
    custom.write_text("custom", encoding="utf-8")
    result = invoke(tmp_path, "update")
    assert result.exit_code == 0, result.output
    assert "custom.mdc" not in result.output
    assert not (custom.parent / "repoize.mdc").exists()
    (tmp_path / ".cursorrules").write_text("legacy", encoding="utf-8")
    result = invoke(tmp_path, "update")
    assert result.exit_code == 1
    assert "迁移" in result.output


@pytest.mark.parametrize("command", ["init", "generate", "update"])
def test_invalid_lang_is_usage_error(tmp_path, command):
    result = invoke(tmp_path, command, "--lang", "fr", "--type", "agents")
