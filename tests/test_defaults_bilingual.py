def test_init_explicit_all_types_creates_six_targets(tmp_path):
    args = ["init", "--lang", "zh"]
    for kind in TARGETS:
        args.extend(["--type", kind])
    result = invoke(tmp_path, *args)
    assert result.exit_code == 0, result.output
    assert "生成 6 个文件" in result.output
    assert all((tmp_path / target).is_file() for target in TARGETS.values())


def test_force_only_replaces_selected_targets(tmp_path):
    (tmp_path / "AGENTS.md").write_text("manual agents", encoding="utf-8")
    (tmp_path / "CLAUDE.md").write_text("manual claude", encoding="utf-8")
    result = invoke(tmp_path, "generate", "--type", "claude", "--force")
    assert result.exit_code == 0, result.output
    assert (tmp_path / "AGENTS.md").read_text(encoding="utf-8") == "manual agents"
    assert "manual claude" not in (tmp_path / "CLAUDE.md").read_text(encoding="utf-8")


def test_update_without_types_updates_existing_and_skips_unmanaged(tmp_path):
    result = invoke(tmp_path, "generate", "--type", "claude", "--lang", "zh")
    assert result.exit_code == 0
    (tmp_path / "AGENTS.md").write_text("manual agents", encoding="utf-8")
    result = invoke(tmp_path, "update")
    assert result.exit_code == 0, result.output
    assert "Project overview" in (tmp_path / "CLAUDE.md").read_text(encoding="utf-8")
    assert (tmp_path / "AGENTS.md").read_text(encoding="utf-8") == "manual agents"
    assert not (tmp_path / ".mcp.json").exists()


def test_declared_and_inferred_commands_show_multiple_locations_without_source_text(tmp_path):
    (tmp_path / "pyproject.toml").write_text(
        '[project]\nname="app"\n[project.optional-dependencies]\ndev=["pytest"]\n'
        '[tool.pytest.ini_options]\naddopts="private-config-value"\n',
        encoding="utf-8",
    )
    analysis = analyze_project(tmp_path)
    content = _load_generator("agents", analysis).generate()
    assert "project.optional-dependencies.dev" in content
    assert "tool.pytest" in content
    assert "private-config-value" not in content
    assert 'pip install -e ".[dev]"' in content


def test_generated_java_commands_use_manifest_runner(tmp_path):
    (tmp_path / "pom.xml").write_text("<project/>", encoding="utf-8")
    (tmp_path / "build.gradle").write_text("plugins { id 'java' }", encoding="utf-8")
    content = _load_generator("agents", analyze_project(tmp_path)).generate()
    assert "mvn test" in content
    assert "gradle test" not in content


def test_generated_js_commands_use_declared_runner(tmp_path):
    (tmp_path / "package.json").write_text(
        json.dumps({"packageManager": "pnpm@9", "scripts": {"test": "vitest"}}), encoding="utf-8"
    )
    content = _load_generator("agents", analyze_project(tmp_path)).generate()
    assert "pnpm run test" in content
    assert "npm run test\n" not in content.replace("pnpm run test", "")
    assert "scripts.test" in content
    assert "not executed" in content


