@pytest.mark.parametrize("kind", TARGETS)
@pytest.mark.parametrize("lang", ["en", "zh"])
def test_cli_every_type_in_both_languages(tmp_path, kind, lang):
    result = invoke(tmp_path, "generate", "--type", kind, "--lang", lang)
    assert result.exit_code == 0, result.output
    content = (tmp_path / TARGETS[kind]).read_text(encoding="utf-8")
    if kind == "mcp":
        assert json.loads(content) == {"mcpServers": {}}
    else:
        assert ("Project overview" if lang == "en" else "项目概述") in content
        assert ("Generated by repoize" if lang == "en" else "本文件由 repoize 自动生成") in content
        if lang == "en":
            assert not any("\u4e00" <= char <= "\u9fff" for char in content)


@pytest.mark.parametrize("kind", ["agents", "claude", "cursor", "copilot", "skill"])
def test_generation_filters_profile_and_renders_sources(tmp_path, kind):
    (tmp_path / "main.py").write_text("pass", encoding="utf-8")
    analysis = analyze_project(tmp_path)
    content = _load_generator(kind, analysis).generate()
    for suggested in ("pytest", "ruff", "python -m build", ".[dev]"):
        assert suggested not in content
    (tmp_path / "pyproject.toml").write_text(
        '[project]\nname="app"\n[tool.pytest.ini_options]\ntestpaths=["tests"]\n', encoding="utf-8"
    )
    analysis = analyze_project(tmp_path)
    content = _load_generator(kind, analysis).generate()
    assert "pytest" in content
    assert "pip install -e ." in content
    assert "not executed" in content
    assert "pyproject.toml" in content
    assert "tool.pytest" in content
    assert ".[dev]" not in content


@pytest.mark.parametrize("kind", ["cursor", "skill"])
def test_language_update_preserves_header_and_manual_bytes(tmp_path, kind):
    result = invoke(tmp_path, "generate", "--type", kind)
    assert result.exit_code == 0, result.output
    output = tmp_path / TARGETS[kind]
    header, body = split_frontmatter(output.read_text(encoding="utf-8"), TARGETS[kind])
    header = header.replace("---\n", "---\ncustom: keep\n", 1)
    output.write_bytes(
        ("\ufeff" + header + "manual prefix\n" + body + "manual suffix\n").replace("\n", "\r\n").encode()
    )
    original_header = output.read_bytes().split(b"manual prefix")[0]
    result = invoke(tmp_path, "update", "--type", kind, "--lang", "zh")
    assert result.exit_code == 0, result.output
    assert output.read_bytes().startswith(original_header + b"manual prefix\r\n")
    assert output.read_bytes().endswith(b"manual suffix\r\n")
    assert "项目概述" in output.read_text(encoding="utf-8")


