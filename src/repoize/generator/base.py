"""生成器基类。"""

import json
from abc import ABC, abstractmethod
from pathlib import Path

from ..analyzer.project_analyzer import ProjectAnalysis
from ..changes import FileChange
from ..formats import GENERATED_END, GENERATED_START, marker_bounds, split_frontmatter
from ..targets import OUTPUT_PATHS, legacy_decision, safe_output_path

GENERATED_BANNER = "<!-- Generated by repoize; edit content outside the managed section. -->"


class BaseGenerator(ABC):
    """配置文件生成器基类。"""

    def __init__(self, analysis: ProjectAnalysis, lang: str = "en"):
        """初始化生成器。"""
        if lang not in {"en", "zh"}:
            raise ValueError("Unsupported language; choose en or zh")
        self.analysis = analysis
        self.lang = lang

    def template_context(self) -> dict:
        """复用项目事实与有证据命令，不把画像建议当仓库配置。"""
        commands = self.analysis.commands.generation_dict()
        sources = {
            (item["category"], item["command"]): [
                source for source in item["sources"] if source["kind"] in {"declared", "inferred"}
            ]
            for item in self.analysis.commands.evidence_dict()
        }
        return {
            "lang": self.lang,
            "project_name": self.analysis.project_name,
            "primary_language": self.analysis.primary_language or ("未知" if self.lang == "zh" else "Unknown"),
            "languages": self.analysis.languages,
            "dependencies": self.analysis.dependencies,
            "frameworks": self.analysis.frameworks,
            "directory_tree": self.analysis.directory_tree,
            "commands": commands,
            "command_sources": sources,
        }

    @property
    @abstractmethod
    def name(self) -> str:
        """生成器名称。"""
        ...

    @property
    @abstractmethod
    def output_filename(self) -> str:
        """相对项目根目录的输出文件名。"""
        ...

    @property
    def is_json(self) -> bool:
        """判断输出是否为 JSON。"""
        return self.output_filename.endswith(".json")

    @abstractmethod
    def generate(self) -> str:
        """渲染完整文件（不含 managed marker）。"""
        ...

    def generate_body(self) -> str:
        """渲染可管理正文，头部只在创建完整文件时写入。"""
        return split_frontmatter(self.generate(), self.output_filename)[1].strip()

    def generate_marked_body(self) -> str:
        """为正文添加生成标记。"""
        banner = (
            "<!-- 本文件由 repoize 自动生成；可修改生成区间之外的内容。 -->" if self.lang == "zh" else GENERATED_BANNER
        )
        return f"{GENERATED_START}\n{banner}\n{self.generate_body()}\n{GENERATED_END}\n"

    def generate_marked(self) -> str:
        """渲染完整文件，frontmatter 始终位于第一行。"""
        header, _ = split_frontmatter(self.generate(), self.output_filename)
        return header + self.generate_marked_body()

    def validate_existing(self, output_path: Path) -> None:
        """已有文件即使将跳过，也不能隐藏损坏格式。"""
        if output_path.exists():
            self._validate_bytes(output_path.read_bytes())

    def _validate_bytes(self, original: bytes) -> None:
        """共享写入与预览的本地格式边界。"""
        content = original.decode("utf-8")
        if self.is_json:
            data = json.loads(content.removeprefix("\ufeff"))
            if not isinstance(data, dict) or not isinstance(data.get("mcpServers", {}), dict):
                raise ValueError("MCP root and mcpServers must be objects")
            if any(not isinstance(server, dict) for server in data.get("mcpServers", {}).values()):
                raise ValueError("Each MCP server must be an object")
        else:
            self._text_bounds(content)

    def _text_bounds(self, content: str) -> tuple[int, int] | None:
        """生成标记必须完整且位于 frontmatter 之后。"""
        bounds = marker_bounds(content)
        header, _ = split_frontmatter(content, self.output_filename)
        if bounds is not None and bounds[0] < len(header):
            raise ValueError("managed marker 不能位于 frontmatter 内")
        return bounds

    def plan(self, project_path: Path, *, mode: str = "generate", force: bool = False) -> FileChange:
        """纯计算候选，不创建目录、不写入文件。"""
        output = safe_output_path(project_path, self.output_filename)
        warning = legacy_decision(project_path, self.output_filename) is not None
        old = output.read_bytes() if output.exists() else None
        if old is not None:
            self._validate_bytes(old)
        kind = next((kind for kind, path in OUTPUT_PATHS.items() if path == self.output_filename), self.name)
        change = FileChange(kind, self.output_filename, "skip", "existing", old_bytes=old, warning=warning)
        if mode == "update":
            if old is None:
                raise FileNotFoundError(f"目标不存在，请先运行 repoize generate: {self.output_filename}")
            if self.is_json:
                previous = json.loads(old.decode("utf-8-sig"))
                generated = json.loads(self.generate())
                merged = {**generated, **previous}
                if isinstance(generated.get("mcpServers"), dict) and isinstance(previous.get("mcpServers"), dict):
                    merged["mcpServers"] = {**generated["mcpServers"], **previous["mcpServers"]}
                new = old if merged == previous else self._json_bytes(merged, old)
            else:
                content = old.decode("utf-8")
                bounds = self._text_bounds(content)
                if bounds is None:
                    change.reason = "unmanaged"
                    return change
                change.comparable = True
                start, end = bounds
                newline = "\r\n" if "\r\n" in content else "\n"
                managed = self.generate_marked_body().removesuffix("\n").replace("\n", newline)
                new = (content[:start] + managed + content[end:]).encode("utf-8")
        else:
            if old is not None and not force:
                return change
            new = (self.generate() if self.is_json else self.generate_marked()).encode("utf-8")
        self._validate_bytes(new)
        change.new_bytes = new
        change.action = "unchanged" if old == new else ("create" if old is None else "update")
        change.reason = "current" if old == new else ("missing" if old is None else "content_changed")
        if self.is_json and old != new:
            change.field_paths = ["$", "mcpServers"]
        return change

    @staticmethod
    def _json_bytes(data: dict, original: bytes) -> bytes:
        """JSON 合并沿用原 BOM 和换行。"""
        newline = "\r\n" if b"\r\n" in original else "\n"
        content = (json.dumps(data, ensure_ascii=False, indent=2) + "\n").replace("\n", newline)
        return (("\ufeff" if original.startswith(b"\xef\xbb\xbf") else "") + content).encode("utf-8")

    def write(self, project_path: Path, force: bool = False) -> Path:
        """兼容已有公开 API，应用纯计算候选。"""
        change = self.plan(project_path, force=force)
        if change.action == "skip":
            raise FileExistsError(f"{change.path} 已存在。使用 --force 覆盖。")
        change.apply(project_path)
        return project_path / change.path

    def update(self, project_path: Path, force: bool = False) -> Path | None:
        """仅替换合法管理区间或合并 JSON，保留旧调用返回值。"""
        change = self.plan(project_path, mode="update")
        if change.action == "skip":
            return None
        change.apply(project_path)
        return project_path / change.path
